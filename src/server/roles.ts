export function buildAgentTemplates(ownerDisplayName = "Owner"): readonly AgentTemplate[] {
  const ownerName = ownerDisplayName.trim();
  if (ownerName.length < 1 || ownerName.length > 80) {
    throw new Error("Owner display name must contain 1-80 characters");
  }
  return BASE_AGENT_TEMPLATES.map((template) =>
    template.agentId === "OWNER-01" ? { ...template, displayName: ownerName } : { ...template },
  );
}

export const AGENT_TEMPLATES: readonly AgentTemplate[] = buildAgentTemplates();

export function getRoleContract(roleId: string): RoleContract {
  const contract = ROLE_CONTRACTS[roleId];
  if (!contract) {
    throw new Error(`Unknown role contract: ${roleId}`);
  }
  return contract;
}
