    outputs: ["bounded decision", "delegated goal", "verification request", "limitations"],
    mayDelegateTo: ["registered descendant roles"],
    mayWriteTo: ["controller goals", "controller messages", "approval requests"],
    approvalRequired: ["external effect", "binding commitment", "scope expansion"],
    definitionOfDone: ["bounded result returned", "limitations recorded", "required checks identified"],
    evaluationSuite: requiredChecks,
    allowedTools: COORDINATION_TOOLS,
    dataAccess: ["public", "internal", "confidential"],
